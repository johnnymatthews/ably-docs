// Shared helpers for the Docs Agent scripts. Plain Node, no dependencies.
import fs from 'node:fs';
import path from 'node:path';

export const DOCS_ROOT = 'src/pages/docs';
export const ALLOWED_PREFIXES = ['src/pages/docs/', 'src/data/nav/'];
export const GENERATED_MARKER = 'AUTOGENERATED';

export const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
export const printJson = (value) => process.stdout.write(`${JSON.stringify(value, null, 2)}\n`);

export function* walk(dir, exts = ['.mdx']) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      yield* walk(full, exts);
    } else if (exts.includes(path.extname(entry.name))) {
      yield full;
    }
  }
}

// camelCase and PascalCase names, for example `setRetryLimit` or `RetryOptions`.
const IDENTIFIER = /\b[a-z][a-z0-9]*[A-Z][A-Za-z0-9]*\b|\b[A-Z][a-z0-9]+(?:[A-Z][a-z0-9]*)+\b/g;

export const identifiers = (text) => new Set(text.match(IDENTIFIER) ?? []);

// Text that counts as "code" in an MDX draft: inline code and fenced block bodies.
// The fence info string (for example `realtime_javascript`) is deliberately excluded.
export function codeText(markdown) {
  const parts = [];
  for (const match of markdown.matchAll(/```[^\n]*\n([\s\S]*?)```/g)) {
    parts.push(match[1]);
  }
  const withoutFences = markdown.replace(/```[^\n]*\n[\s\S]*?```/g, '');
  for (const match of withoutFences.matchAll(/`([^`\n]+)`/g)) {
    parts.push(match[1]);
  }
  return parts.join('\n');
}

// Page URL for a content file, for example src/pages/docs/push/index.mdx -> /docs/push
export const pageUrl = (file) =>
  `/${file.replace(/^src\/pages\//, '').replace(/\.mdx$/, '').replace(/\/index$/, '')}`;

// Apply exact find-and-replace patches. Each find string must match exactly once, otherwise it is reported and skipped.
export function applyReplacements(text, replacements) {
  let out = text;
  const errors = [];
  for (const { find, replace } of replacements) {
    const count = find ? out.split(find).length - 1 : 0;
    if (count !== 1) {
      errors.push(`"${String(find).slice(0, 60)}" matched ${count} times, expected exactly 1`);
      continue;
    }
    out = out.replace(find, () => replace);
  }
  return { text: out, errors };
}

export const addedLines = (patch) =>
  patch
    .split('\n')
    .filter((line) => line.startsWith('+') && !line.startsWith('+++'))
    .map((line) => line.slice(1))
    .join('\n');

// Plain-text rendering of the comment and PR body, so the dry run and the live run agree.
export const COMMENT_MARKER = '<!-- docs-agent:v1 -->';

export function renderComment({ summary, draftUrl, previewUrl, notSure }) {
  const clip = (text) => (text.length > 90 ? `${text.slice(0, 87).trimEnd()}...` : text.replace(/\.$/, ''));
  const shown = notSure.slice(0, 2).map(clip);
  const more = notSure.length > shown.length ? ` (and ${notSure.length - shown.length} more, listed on the draft PR)` : '';
  const unsure = notSure.length ? `${shown.join('; ')}${more}` : 'nothing I could identify';
  const preview = previewUrl ? ` (preview: ${previewUrl})` : '';
  return `${COMMENT_MARKER}
Hi, I'm the Docs Agent. ${summary}
I've drafted docs here: ${draftUrl}${preview}.
I'm not sure about: ${unsure}.

If that's right, 👍 this comment. If I've got it wrong, reply starting with \`docs:\` and I'll revise once.
Ignore this and Docs Engineering will pick it up.
`;
}

export function renderPrBody({ source, draft, routing, verification }) {
  const files = draft.edits.map((edit) => `- \`${edit.path}\` (drafted)`);
  for (const page of routing.pages.filter((p) => p.lane === 'generated')) {
    files.push(`- \`${page.path}\` (generated, not edited by the agent)`);
  }
  const unsure = verification.not_sure.length
    ? verification.not_sure.map((item) => `- ${item}`).join('\n')
    : '- Nothing flagged';
  const warnings = routing.warnings.length ? routing.warnings.map((w) => `- ${w}`).join('\n') : '- None';
  return `Source PR: ${source.url}
Drafted by the Docs Agent. A person must review before merge.

**Summary:** ${draft.summary}

**Files changed**
${files.join('\n')}

**Not sure about**
${unsure}

**Source-of-truth warnings**
${warnings}

**Verification:** ${verification.claims_checked} claims checked, ${verification.claims_failed} failed. Names in code samples not found in the PR or existing docs: ${verification.symbols_failed}. Edits rejected: ${verification.rejected_edits.length}.
**Engineer response:** none yet

### Checklist

- [ ] Commits have been rebased.
- [ ] Linting has been run against the changed file(s).
- [ ] The PR adheres to the [writing style guide](../blob/main/writing-style-guide.md) and [contribution guide](../blob/main/CONTRIBUTING.md).
`;
}
