// Step 4: check the draft with plain code, not the model.
//   node scripts/docs-agent/verify.mjs draft.json routed.json > verified.json
// Failures never block the draft. They move claims onto the "not sure" list and set a flag.
import fs from 'node:fs';
import path from 'node:path';
import {
  ALLOWED_PREFIXES,
  DOCS_ROOT,
  GENERATED_MARKER,
  codeText,
  identifiers,
  printJson,
  readJson,
  walk,
} from './lib.mjs';

const draft = readJson(process.argv[2]);
const routed = readJson(process.argv[3]);

const failures = [];
let claimFailures = 0;
let symbolFailures = 0;
const rejectedEdits = [];
const notSure = [...draft.not_sure];

// Known names: anything in the PR (patches, title, body) or already in the docs.
const known = identifiers(
  [routed.source.title, routed.source.body, ...routed.source.files.map((file) => file.patch)].join('\n'),
);
for (const file of walk(DOCS_ROOT)) {
  for (const name of identifiers(fs.readFileSync(file, 'utf8'))) {
    known.add(name);
  }
}

// Check 3: allow-listed paths only, and generated files are off limits.
const edits = [];
for (const edit of draft.edits) {
  const normal = path.posix.normalize(edit.path);
  const escapes = normal.startsWith('..') || path.isAbsolute(normal);
  if (escapes || !ALLOWED_PREFIXES.some((prefix) => normal.startsWith(prefix))) {
    rejectedEdits.push({ path: edit.path, reason: 'outside the allow-listed paths' });
    continue;
  }
  if (fs.existsSync(normal) && fs.readFileSync(normal, 'utf8').includes(GENERATED_MARKER)) {
    rejectedEdits.push({ path: edit.path, reason: 'file is generated (AUTOGENERATED marker); only its generator may change it' });
    continue;
  }
  edits.push({ ...edit, path: normal });
}

// Check 1: every identifier in code must exist in the PR or the existing docs.
for (const edit of edits) {
  for (const name of identifiers(codeText(edit.content))) {
    if (!known.has(name)) {
      symbolFailures += 1;
      failures.push(`\`${name}\` in ${edit.path} appears in neither the PR nor the existing docs`);
      notSure.push(`Whether \`${name}\` exists (not found in the PR or the existing docs)`);
    }
  }
}

// Check 2: every claim needs evidence that resolves to a changed file naming what it claims.
let claimsChecked = 0;
for (const claim of draft.claims) {
  claimsChecked += 1;
  const target = /^patch:(.+)$/.exec(claim.evidence ?? '')?.[1];
  const file = routed.source.files.find((candidate) => candidate.path === target);
  if (!file) {
    claimFailures += 1;
    failures.push(`Claim has no resolvable evidence: "${claim.text}"`);
    notSure.push(claim.text);
    continue;
  }
  const missing = [...identifiers(claim.text)].filter((name) => !file.patch.includes(name));
  if (missing.length > 0) {
    claimFailures += 1;
    failures.push(`Claim cites ${target} but that patch lacks ${missing.join(', ')}: "${claim.text}"`);
    notSure.push(claim.text);
  }
}

printJson({
  ...draft,
  edits,
  verification: {
    claims_checked: claimsChecked,
    claims_failed: claimFailures,
    symbols_failed: symbolFailures,
    failures,
    rejected_edits: rejectedEdits,
    not_sure: [...new Set(notSure)],
    needs_human_attention: failures.length > 0 || rejectedEdits.length > 0 || routed.routing.warnings.length > 0,
  },
  routing: routed.routing,
  source: routed.source,
});
